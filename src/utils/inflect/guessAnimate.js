/**
 * Определяет одушевлённость существительного.
 * 1. Сначала — словарь nounExceptions (там тоже бывает animate).
 * 2. Потом — ANIMATE_WORDS.
 * 3. Если не найдено — неодушевлённое.
 *
 * @param {string} word
 * @returns {boolean}
 */
export function guessAnimate(word) {
  if (!word) return false;
  const w = word.trim().toLowerCase().replace(/ё/g, 'е');
  if (!w) return false;

  if (nounExceptions[w] && nounExceptions[w].animate !== undefined) {
    return nounExceptions[w].animate;
  }

  return ANIMATE_WORDS.has(w);
}