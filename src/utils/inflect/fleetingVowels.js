/**
 * Возвращает запись с готовыми формами Род./Дат./Тв./Пр.
 * Или null, если слово не в словаре.
 *
 * @param {string} word
 * @returns {{ gen, dat, ins, pre } | null}
 */
export function getFleetingEntry(word) {
  if (!word) return null;
  const w = word.trim().toLowerCase().replace(/ё/g, 'е');
  return FLEETING_VOWELS[w] || null;
}
