/**
 * Проверяет, является ли слово несклоняемым.
 * @param {string} word
 * @returns {boolean}
 */
export function isIndeclinable(word) {
  if (!word) return false;
  const w = word.trim().toLowerCase().replace(/ё/g, 'е');
  return INDECLINABLE.has(w);
}
